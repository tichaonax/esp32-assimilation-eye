"""PlatformIO pre-build script: record when this firmware was built.

Writes src/generated/build_info.h, which only src/BuildInfo.cpp includes, so
the time shown on the System screen is the time of this build and not the last
time some particular source file happened to be compiled.
"""
import os
import time

Import("env")  # noqa: F821  (provided by PlatformIO)

if not env.IsIntegrationDump():  # noqa: F821
    header = os.path.join(env.subst("$PROJECT_DIR"), "src", "generated", "build_info.h")  # noqa: F821
    os.makedirs(os.path.dirname(header), exist_ok=True)
    stamp = time.strftime("%Y-%m-%d %H:%M")
    with open(header, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("// Generated by scripts/build_info.py. Do not edit; do not commit.\n")
        handle.write("#pragma once\n")
        handle.write(f'#define BUILD_TIMESTAMP "{stamp}"\n')
